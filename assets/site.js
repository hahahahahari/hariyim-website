function setLang(lang) {
  if (!I18N[lang]) return;
  localStorage.setItem('hari-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = I18N[lang][el.dataset.i18n];
    if (value != null) el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const value = I18N[lang][el.dataset.i18nPlaceholder];
    if (value != null) el.placeholder = value;
  });
  document.querySelectorAll('[data-lang]').forEach(btn => btn.classList.toggle('active', btn.dataset.lang === lang));
}

function initNav() {
  const btn = document.querySelector('.nav-toggle');
  const links = document.querySelector('.nav-links');
  if (!btn || !links) return;
  btn.addEventListener('click', () => {
    const open = links.classList.toggle('open');
    btn.setAttribute('aria-expanded', String(open));
    document.body.classList.toggle('menu-open', open);
  });
  links.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
    links.classList.remove('open'); document.body.classList.remove('menu-open'); btn.setAttribute('aria-expanded','false');
  }));
}

function initLanguage() {
  document.querySelectorAll('[data-lang]').forEach(btn => btn.addEventListener('click', () => setLang(btn.dataset.lang)));
  setLang(localStorage.getItem('hari-lang') || 'en');
}

function canonicalizeIndex() {
  if (location.protocol.startsWith('http') && location.pathname.endsWith('/index.html')) {
    history.replaceState({}, '', location.pathname.replace(/index\.html$/, '') + location.search + location.hash);
  }
}

document.addEventListener('DOMContentLoaded', () => {
  initNav(); initLanguage(); canonicalizeIndex();
});
